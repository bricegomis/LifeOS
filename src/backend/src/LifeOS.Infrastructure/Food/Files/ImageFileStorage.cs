using System.Security.Cryptography;
using LifeOS.Application.Food.Receipts;
using Microsoft.Extensions.Options;

namespace LifeOS.Infrastructure.Food.Files;

public sealed class FoodImageStorageOptions
{
    public string StoragePath { get; set; } = "/data/foods";
    public long MaxFileBytes { get; set; } = 10 * 1024 * 1024;
}

public sealed class ReceiptPhotoStorageOptions
{
    public string StoragePath { get; set; } = "/data/receipts";
    public long MaxFileBytes { get; set; } = 10 * 1024 * 1024;
}

/// <summary>Food and recipe images (volume <c>lifeos_food_images</c>).</summary>
public sealed class FoodImageStorage(IOptions<FoodImageStorageOptions> options)
    : ImageFileStorage(options.Value.StoragePath, options.Value.MaxFileBytes, 10 * 1024 * 1024);

/// <summary>Receipt photos (volume <c>lifeos_receipts</c>).</summary>
public sealed class ReceiptPhotoStorage(IOptions<ReceiptPhotoStorageOptions> options)
    : ImageFileStorage(options.Value.StoragePath, options.Value.MaxFileBytes, 25 * 1024 * 1024), IReceiptPhotoFiles;

/// <summary>
/// Stores JPEG, PNG or WebP files under a fixed root. The name is generated by the server, the
/// declared type must match the file signature and the size limit is enforced while streaming.
/// </summary>
public abstract class ImageFileStorage
{
    public const long DefaultMaxFileBytes = 10 * 1024 * 1024;
    private const int BufferSize = 81920;
    private readonly string _root;
    private readonly long _maxBytes;

    protected ImageFileStorage(string storagePath, long configuredMaxBytes, long ceilingBytes)
    {
        _root = Path.GetFullPath(storagePath);
        _maxBytes = configuredMaxBytes > 0 && configuredMaxBytes <= ceilingBytes ? configuredMaxBytes : DefaultMaxFileBytes;
    }

    public async Task<StoredFile> SaveAsync(Stream content, long length, string? declaredContentType, CancellationToken cancellationToken)
    {
        var limit = $"{_maxBytes / 1024 / 1024} Mo";
        if (length <= 0 || length > _maxBytes)
            throw new ArgumentException($"L'image doit peser entre 1 octet et {limit}.");

        var contentType = (declaredContentType ?? "").ToLowerInvariant();
        var extension = contentType switch
        {
            "image/jpeg" => ".jpg",
            "image/png" => ".png",
            "image/webp" => ".webp",
            _ => throw new ArgumentException("Formats acceptés : JPEG, PNG et WebP.")
        };

        var signature = new byte[12];
        var signatureLength = 0;
        while (signatureLength < signature.Length)
        {
            var read = await content.ReadAsync(signature.AsMemory(signatureLength), cancellationToken);
            if (read == 0) break;
            signatureLength += read;
        }
        if (!HasValidSignature(contentType, signature.AsSpan(0, signatureLength)))
            throw new ArgumentException("Le contenu du fichier ne correspond pas à son type d'image.");

        Directory.CreateDirectory(_root);
        var fileName = $"{Guid.NewGuid():N}{extension}";
        var path = ResolvePath(fileName);
        using var hash = IncrementalHash.CreateHash(HashAlgorithmName.SHA256);
        await using var destination = new FileStream(path, FileMode.CreateNew, FileAccess.Write, FileShare.None, BufferSize, true);
        try
        {
            hash.AppendData(signature, 0, signatureLength);
            await destination.WriteAsync(signature.AsMemory(0, signatureLength), cancellationToken);
            long total = signatureLength;
            var buffer = new byte[BufferSize];
            while (true)
            {
                var read = await content.ReadAsync(buffer, cancellationToken);
                if (read == 0) break;
                total += read;
                if (total > _maxBytes) throw new ArgumentException($"L'image dépasse la limite de {limit}.");
                hash.AppendData(buffer, 0, read);
                await destination.WriteAsync(buffer.AsMemory(0, read), cancellationToken);
            }
            await destination.FlushAsync(cancellationToken);
        }
        catch
        {
            await destination.DisposeAsync();
            File.Delete(path);
            throw;
        }

        return new StoredFile(fileName, contentType, Convert.ToHexString(hash.GetHashAndReset()));
    }

    public string ResolvePath(string fileName)
    {
        if (string.IsNullOrWhiteSpace(fileName) || Path.GetFileName(fileName) != fileName)
            throw new ArgumentException("Référence d'image invalide.");
        var path = Path.GetFullPath(Path.Combine(_root, fileName));
        if (!path.StartsWith(_root + Path.DirectorySeparatorChar, StringComparison.Ordinal))
            throw new ArgumentException("Référence d'image invalide.");
        return path;
    }

    public bool Exists(string fileName) => File.Exists(ResolvePath(fileName));

    public void Delete(string fileName)
    {
        var path = ResolvePath(fileName);
        if (File.Exists(path)) File.Delete(path);
    }

    /// <summary>Deletes a replaced file; a failure is only logged since the database no longer points to it.</summary>
    public void DeleteQuietly(string? fileName, Action<Exception> onError)
    {
        if (fileName is null) return;
        try { Delete(fileName); }
        catch (Exception exception) when (exception is IOException or UnauthorizedAccessException) { onError(exception); }
    }

    public FileStream OpenRead(string fileName) =>
        new(ResolvePath(fileName), FileMode.Open, FileAccess.Read, FileShare.Read, BufferSize, true);

    private static bool HasValidSignature(string contentType, ReadOnlySpan<byte> bytes) => contentType switch
    {
        "image/jpeg" => bytes.Length >= 3 && bytes[0] == 0xFF && bytes[1] == 0xD8 && bytes[2] == 0xFF,
        "image/png" => bytes.Length >= 8 && bytes[..8].SequenceEqual(new byte[] { 137, 80, 78, 71, 13, 10, 26, 10 }),
        "image/webp" => bytes.Length >= 12 && bytes[..4].SequenceEqual("RIFF"u8) && bytes[8..12].SequenceEqual("WEBP"u8),
        _ => false
    };
}
