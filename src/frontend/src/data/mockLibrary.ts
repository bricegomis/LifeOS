const dishSuitabilityByMealType = {
  breakfast: 'suitableForBreakfast',
  lunch: 'suitableForLunch',
  dinner: 'suitableForDinner',
} as const

export function componentsByType(componentType: ComponentType): MealComponent[] {
  return mealComponents.filter(
    (component) => component.componentType === componentType && component.active,
  )
}

export function dishesForMealType(mealType: MealType): CompositeDish[] {
  const suitabilityKey = dishSuitabilityByMealType[mealType]

  return compositeDishes.filter((dish) => dish.active && dish[suitabilityKey])
}
